def _samplewise_bounds(x: torch.Tensor) -> Tuple[torch.Tensor, torch.Tensor]:
    dims = tuple(range(1, x.ndim))
    return x.amin(dim=dims, keepdim=True), x.amax(dim=dims, keepdim=True)


def fgsm(
    model: torch.nn.Module,
    x: torch.Tensor,
    y: torch.Tensor,
    eps: float,
    num_classes: int,
) -> torch.Tensor:
    if math.isclose(eps, 0.0, abs_tol=1e-12):
        return x.detach().clone()
    x_adv = x.detach().clone().requires_grad_(True)
    loss = dice_ce_loss(model(x_adv), y, num_classes)
    model.zero_grad(set_to_none=True)
    loss.backward()
    x_out = x.detach() + eps * x_adv.grad.detach().sign()
    lo, hi = _samplewise_bounds(x)
    return x_out.clamp(lo, hi).detach()


def pgd_bce(
    model: torch.nn.Module,
    x: torch.Tensor,
    y: torch.Tensor,
    eps: float,
    num_classes: int,
    n_steps: int = 10,
) -> torch.Tensor:
    if math.isclose(eps, 0.0, abs_tol=1e-12):
        return x.detach().clone()
    alpha = eps / max(n_steps, 1)
    lo, hi = _samplewise_bounds(x)
    x_det = x.detach()
    x_adv = x_det.clone()
    for _ in range(n_steps):
        x_adv = x_adv.requires_grad_(True)
        loss = bce_loss(model(x_adv), y, num_classes)
        model.zero_grad(set_to_none=True)
        loss.backward()
        with torch.no_grad():
            x_adv = x_adv + alpha * x_adv.grad.sign()
            x_adv = x_adv.clamp(x_det - eps, x_det + eps).clamp(lo, hi).detach()
    return x_adv


def apgd_bce(
    model: torch.nn.Module,
    x: torch.Tensor,
    y: torch.Tensor,
    eps: float,
    num_classes: int,
    n_steps: int = 20,
    perturbation_mask: torch.Tensor | None = None,
) -> torch.Tensor:
    """APGD-BCE (Croce & Hein 2020): momentum + monotone step-size halving schedule.

    ``perturbation_mask`` (bool, broadcastable to ``x``) confines the perturbation
    to True voxels; ``None`` leaves the behaviour unchanged.
    """
    if math.isclose(eps, 0.0, abs_tol=1e-12):
        return x.detach().clone()

    def _confine(adv: torch.Tensor) -> torch.Tensor:
        return adv if perturbation_mask is None else torch.where(perturbation_mask, adv, x_det)

    lo, hi = _samplewise_bounds(x)
    x_det = x.detach()
    x_adv = _confine((x_det + torch.empty_like(x_det).uniform_(-eps, eps)).clamp(lo, hi))
    x_best = x_adv.clone()

    alpha = 2.0 * eps  # initial step size per APGD paper

    # Checkpoint schedule: first at ceil(0.22*n_steps), then 0.22 of remaining
    checkpoints = []
    w = max(1, math.ceil(0.22 * n_steps))
    checkpoints.append(w)
    while checkpoints[-1] < n_steps:
        remaining = n_steps - checkpoints[-1]
        w = max(1, math.ceil(0.22 * remaining))
        checkpoints.append(min(checkpoints[-1] + w, n_steps))
    ck_idx = 0

    best_loss = -float("inf")
    sum_loss = 0.0
    n_sum = 0

    for step in range(1, n_steps + 1):
        x_req = x_adv.clone().requires_grad_(True)
        loss = bce_loss(model(x_req), y, num_classes)
        model.zero_grad(set_to_none=True)
        loss.backward()

        with torch.no_grad():
            loss_val = loss.item()
            sum_loss += loss_val
            n_sum += 1

            # Gradient step + L∞ projection
            z = (
                (x_adv + alpha * x_req.grad.detach().sign())
                .clamp(x_det - eps, x_det + eps)
                .clamp(lo, hi)
            )
            # Momentum: convex combination α=0.75 (Croce & Hein convention)
            x_new = _confine(
                (0.75 * z + 0.25 * x_adv).clamp(x_det - eps, x_det + eps).clamp(lo, hi)
            )

            if loss_val > best_loss:
                best_loss = loss_val
                x_best = x_new.clone()

            x_adv = x_new

        # Halve step size at checkpoint if progress is insufficient
        if ck_idx < len(checkpoints) and step == checkpoints[ck_idx]:
            avg = sum_loss / n_sum if n_sum > 0 else 0.0
            if avg <= best_loss * 0.95:
                alpha = alpha * 0.5
            sum_loss = 0.0
            n_sum = 0
            ck_idx += 1

    return x_best.detach()


