def pad_to_divisible(
    x: torch.Tensor, div_factors: List[int]
) -> Tuple[torch.Tensor, Tuple]:
    orig = tuple(x.shape[2:])
    pad = []
    for d in reversed(range(len(orig))):
        f = div_factors[d]
        r = orig[d] % f
        pad.extend([0, (f - r) % f])
    if any(p > 0 for p in pad):
        x = F.pad(x, pad)
    return x, orig


def unpad(x: torch.Tensor, orig_shape: Tuple) -> torch.Tensor:
    return x[tuple([slice(None), slice(None)] + [slice(0, s) for s in orig_shape])]


# ---------------------------------------------------------------------------
# Combined Dice+CE loss for attacks
# ---------------------------------------------------------------------------
def dice_ce_loss(
    logits: torch.Tensor, target: torch.Tensor, num_classes: int
) -> torch.Tensor:
    if num_classes == 2:
        t = target.squeeze(1).long()
        ce = F.cross_entropy(logits, t, ignore_index=IGNORE_LABEL)
        probs = F.softmax(logits, dim=1)
        p_fg = probs[:, 1:2]
        valid = (t != IGNORE_LABEL).float().unsqueeze(1)
        t_fg = (t == 1).float().unsqueeze(1) * valid
        p_fg = p_fg * valid
        inter = (p_fg * t_fg).sum()
        denom = p_fg.sum() + t_fg.sum()
        dice_loss = 1.0 - (2.0 * inter + 1e-5) / (denom + 1e-5)
    else:
        t_long = target.squeeze(1).long()
        ce = F.cross_entropy(logits, t_long, ignore_index=IGNORE_LABEL)
        t = target.squeeze(1)
        valid = (t != IGNORE_LABEL).float()
        dice_loss = torch.tensor(0.0, device=logits.device)
        for c in range(1, num_classes):
            p_c = torch.softmax(logits, dim=1)[:, c]
            t_c = (t == c).float() * valid
            inter = (p_c * t_c).sum()
            denom = (p_c * valid).sum() + t_c.sum()
            dice_loss = dice_loss + 1.0 - (2.0 * inter + 1e-5) / (denom + 1e-5)
        dice_loss = dice_loss / (num_classes - 1)
    return dice_loss + ce


def bce_loss(
    logits: torch.Tensor, target: torch.Tensor, num_classes: int
) -> torch.Tensor:
    """Per-voxel BCE-with-logits loss over one-hot targets, masking IGNORE_LABEL."""
    t = target.squeeze(1).long()
    valid = (t != IGNORE_LABEL).unsqueeze(1).float()
    t_safe = t.clamp_min(0)
    y_oh = torch.zeros_like(logits)
    y_oh.scatter_(1, t_safe.unsqueeze(1), 1.0)
    y_oh = y_oh * valid
    loss_per_el = F.binary_cross_entropy_with_logits(logits, y_oh, reduction="none")
    n_valid = valid.expand_as(loss_per_el).sum().clamp(min=1.0)
    return (loss_per_el * valid).sum() / n_valid


