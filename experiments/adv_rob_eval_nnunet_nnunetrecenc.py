def _pad_to(
    t: torch.Tensor, target: List[int], mode: str = "constant", value: float = 0.0
):
    """Pad the spatial dims (D,H,W) of a [1,C,D,H,W] tensor up to ``target``."""
    d, h, w = t.shape[2:]
    pad = [0, target[2] - w, 0, target[1] - h, 0, target[0] - d]
    if mode == "replicate":
        return F.pad(t, pad, mode="replicate")
    return F.pad(t, pad, mode="constant", value=value)


def _case_dhw(data_dir: str, case_id: str) -> tuple:
    """Cheap (metadata-only where possible) spatial shape (D,H,W) of a case."""
    b2nd = os.path.join(data_dir, f"{case_id}.b2nd")
    if os.path.isfile(b2nd):
        import blosc2

        return tuple(blosc2.open(urlpath=b2nd, mode="r").shape[1:])
    npy = os.path.join(data_dir, f"{case_id}.npy")
    if os.path.isfile(npy):
        return tuple(np.load(npy, mmap_mode="r").shape[1:])
    img, _, _ = load_sample(data_dir, case_id)
    return tuple(np.asarray(img).shape[1:])


def _plan_batches(
    data_dir: str, case_ids: List[str], div_factors: List[int], batch_size: int
) -> List[List[str]]:
    """Group case_ids so a batch holds only cases with an identical padded
    (divisible) shape. Each case is then padded exactly as it would be at
    batch_size=1, so batching never changes a result. Cases whose shape cannot
    be read are processed alone (the error surfaces at load time)."""
    if batch_size <= 1:
        return [[cid] for cid in case_ids]
    from collections import OrderedDict

    groups: OrderedDict = OrderedDict()
    for cid in case_ids:
        try:
            dhw = _case_dhw(data_dir, cid)
            key = tuple(int(math.ceil(v / f) * f) for v, f in zip(dhw, div_factors))
        except Exception:
            key = ("_err_", cid)
        groups.setdefault(key, []).append(cid)
    batches: List[List[str]] = []
    for grp in groups.values():
        for i in range(0, len(grp), batch_size):
            batches.append(grp[i : i + batch_size])
    return batches


def evaluate_fold(
    model: torch.nn.Module,
    div_factors: List[int],
    num_classes: int,
    data_dir: str,
    case_ids: List[str],
    epsilons: List[float],
    device: torch.device,
    max_cases: int | None,
    attacks: Dict | None = None,
    batch_size: int = 1,
    autocast_dtype: torch.dtype | None = None,
) -> tuple[Dict, List[str]]:
    """Return (results, case_order).

    ``results``: nested dict attack → epsilon → metric → [per-case macro values].
    ``case_order``: the case_ids actually evaluated, in the same order as the
    per-case lists (a case that fails ``load_sample`` is skipped before any
    append, so the lists and ``case_order`` stay aligned).

    Up to ``batch_size`` cases are attacked per forward, but only cases with an
    identical padded (divisible) shape are batched together (see
    ``_plan_batches``). Each case is therefore padded exactly as it would be at
    ``batch_size=1`` — image with zeros, label with ``IGNORE_LABEL`` — so its
    inputs, attack, and unpadded prediction are bit-for-bit what it gets alone.
    ``batch_size`` is thus a pure throughput knob that does not change any
    reported metric; it only groups same-shape cases to fill the GPU. (Batching
    across *different* shapes would pad the smaller volumes and leak padding into
    boundary predictions — measured at up to ~1.6% Dice on Zones — which is why
    only same-shape cases share a batch.)

    ``autocast_dtype`` (e.g. ``torch.bfloat16``) wraps only the attack generation
    in ``torch.autocast``; the reported metric forward stays fp32 so the recorded
    Dice is what the fp32 model predicts on the perturbation. It is an
    approximation knob — unlike ``batch_size`` it *can* shift the reported metric
    slightly, so validate the drift with ``measure_bf16_autocast.py`` first.
    ``None`` (default) runs everything in fp32.
    """
    attacks = attacks if attacks is not None else ATTACKS
    fg_classes = list(range(1, num_classes))
    if max_cases is not None:
        case_ids = case_ids[:max_cases]

    results = {
        atk: {eps: {m: [] for m in METRICS} for eps in epsilons} for atk in attacks
    }
    case_order: List[str] = []

    for batch_cids in _plan_batches(data_dir, case_ids, div_factors, batch_size):
        loaded = []
        for cid in batch_cids:
            try:
                img_np, seg_np, spacing = load_sample(data_dir, cid)
            except Exception as e:
                print(f"    [skip] {cid}: {e}")
                continue
            loaded.append((cid, img_np, np.asarray(seg_np), spacing))
        if not loaded:
            continue

        # Common padded shape (batch-max, made divisible). Because a batch holds
        # only same-shape cases, this equals each case's own divisible shape.
        dims = [rec[1].shape[1:] for rec in loaded]  # (D,H,W) per case
        maxdhw = [max(d[k] for d in dims) for k in range(3)]
        target = [int(math.ceil(v / f) * f) for v, f in zip(maxdhw, div_factors)]

        xb, yb, origs, gts, spacings = [], [], [], [], []
        for _cid, img_np, seg_np, spacing in loaded:
            x = torch.from_numpy(img_np[np.newaxis]).to(device)
            y = torch.from_numpy(seg_np[np.newaxis].astype(np.float32)).to(device)
            xb.append(_pad_to(x, target))  # zeros: matches conv zero-padding
            yb.append(_pad_to(y, target, mode="constant", value=float(IGNORE_LABEL)))
            origs.append(tuple(img_np.shape[1:]))
            gt = seg_np.squeeze()
            if gt.ndim == 4:
                gt = gt[0]
            gts.append(gt)
            spacings.append(spacing)
        x_batch = torch.cat(xb, dim=0)
        y_batch = torch.cat(yb, dim=0)
        del xb, yb

        # GPU phase: attack the whole batch, unpad each sample, store on CPU.
        preds: dict = {}
        for atk_name, atk_fn in attacks.items():
            for eps in epsilons:
                # Autocast (if requested) covers ONLY generation; the metric
                # forward below stays fp32 so the reported Dice is the fp32
                # model's prediction on the perturbation.
                gen_cast = (
                    torch.autocast(device_type=device.type, dtype=autocast_dtype)
                    if autocast_dtype is not None
                    else contextlib.nullcontext()
                )
                with torch.enable_grad(), gen_cast:
                    x_adv = atk_fn(model, x_batch, y_batch, eps, num_classes)
                with torch.no_grad():
                    pred_b = model(x_adv).argmax(dim=1).cpu().numpy().astype(np.int64)
                preds[(atk_name, eps)] = [
                    pred_b[bi, : o[0], : o[1], : o[2]] for bi, o in enumerate(origs)
                ]
                del x_adv

        del x_batch, y_batch
        if device.type == "cuda":
            torch.cuda.empty_cache()

        # CPU phase: per-case metrics (unpadded predictions vs original GT).
        for bi, (cid, _img, _seg, _sp) in enumerate(loaded):
            gt, spacing = gts[bi], spacings[bi]
            for (atk_name, eps), per_sample in preds.items():
                pred = per_sample[bi]
                per_cls = {}
                for c in fg_classes:
                    pb = (pred == c).astype(np.uint8)
                    gb = (gt == c).astype(np.uint8)
                    dice, hd95, asd = class_metrics_triple(
                        pb, gb, voxel_spacing=spacing
                    )
                    iou = iou_score(pb, gb)
                    per_cls[c] = {"dice": dice, "hd95": hd95, "asd": asd, "iou": iou}
                for m in METRICS:
                    results[atk_name][eps][m].append(macro_mean(per_cls, m))
            case_order.append(cid)

        print(f"    case {len(case_order)}/{len(case_ids)}")

    return results, case_order


