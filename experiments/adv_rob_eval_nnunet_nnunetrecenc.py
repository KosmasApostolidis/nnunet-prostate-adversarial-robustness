def load_sample(data_dir: str, case_id: str) -> Tuple[np.ndarray, np.ndarray, tuple]:
    """Return (image float32 [C,D,H,W], seg int [1,D,H,W], spacing_zyx tuple)."""
    b2nd_path = os.path.join(data_dir, f"{case_id}.b2nd")
    seg_b2nd = os.path.join(data_dir, f"{case_id}_seg.b2nd")
    npy_path = os.path.join(data_dir, f"{case_id}.npy")
    seg_npy = os.path.join(data_dir, f"{case_id}_seg.npy")
    npz_path = os.path.join(data_dir, f"{case_id}.npz")
    pkl_path = os.path.join(data_dir, f"{case_id}.pkl")

    if os.path.isfile(b2nd_path):
        import blosc2

        img = np.asarray(blosc2.open(urlpath=b2nd_path, mode="r")[:], dtype=np.float32)
        seg = np.asarray(blosc2.open(urlpath=seg_b2nd, mode="r")[:])
    elif os.path.isfile(npy_path):
        img = np.load(npy_path).astype(np.float32)
        seg = np.load(seg_npy)
    elif os.path.isfile(npz_path):
        data = np.load(npz_path)
        img = data["data"].astype(np.float32)
        seg = data["seg"]
    else:
        raise FileNotFoundError(f"No data file for {case_id} in {data_dir}")

    spacing = (1.0, 1.0, 1.0)
    if os.path.isfile(pkl_path):
        # Safe: .pkl written by nnU-Net's own preprocessing; lives in our local
        # nnUNet_preprocessed directory and is never user-supplied input.
        with open(pkl_path, "rb") as f:
            props = pickle.load(f)
        raw = props.get("spacing", spacing)
        spacing = tuple(float(v) for v in raw)

    return img, seg, spacing


