def _resolve_class(fqn: str):
    module_path, cls_name = fqn.rsplit(".", 1)
    return getattr(import_module(module_path), cls_name)


def _strip_prefix(state_dict: dict) -> dict:
    out = {}
    for k, v in state_dict.items():
        key = k
        for prefix in ("_orig_mod.", "module."):
            if key.startswith(prefix):
                key = key[len(prefix) :]
        out[key] = v
    return out


def build_model(
    ckpt_path: str, device: torch.device
) -> Tuple[torch.nn.Module, List[int], int]:
    """Load a checkpoint into the correct architecture (UNet or ResidualEncoderUNet).

    Returns (model, div_factors, num_classes).
    """
    # weights_only=False required: nnU-Net checkpoints store init_args (plans,
    # dataset_json, configuration) as nested dicts alongside tensor weights —
    # not pure-tensor files. These checkpoints are generated by our own training
    # pipeline and are never user-supplied.
    ckpt = torch.load(ckpt_path, map_location="cpu", weights_only=False)
    plans = ckpt["init_args"]["plans"]
    configuration = ckpt["init_args"]["configuration"]

    arch = plans["configurations"][configuration]["architecture"]
    net_cls = _resolve_class(arch["network_class_name"])

    arch_kwargs = dict(arch["arch_kwargs"])
    for key in arch.get("_kw_requires_import", []):
        if arch_kwargs.get(key) is not None:
            arch_kwargs[key] = _resolve_class(arch_kwargs[key])

    dataset_json = ckpt["init_args"]["dataset_json"]
    num_classes = len(dataset_json["labels"])
    input_channels = len(dataset_json["channel_names"])

    arch_kwargs["input_channels"] = input_channels
    arch_kwargs["num_classes"] = num_classes
    arch_kwargs["deep_supervision"] = False

    strides = arch_kwargs["strides"]
    ndim = len(strides[0])
    div_factors = [1] * ndim
    for s in strides:
        for d in range(ndim):
            div_factors[d] *= s[d]

    net = net_cls(**arch_kwargs)
    net.load_state_dict(_strip_prefix(ckpt["network_weights"]), strict=True)
    net.eval().to(device)
    return net, div_factors, num_classes


