def plot_2x2(
    fold_results: Dict[int, Dict],
    epsilons: List[float],
    title: str,
    attack_name: str,
    out_path: str,
) -> None:
    """1×3 grid: one subplot per metric (Dice, HD95, ASD), one line per fold, black macro-avg."""
    fig, axes = plt.subplots(1, 3, figsize=(16, 5))
    fig.suptitle(title, fontsize=13, fontweight="bold", y=1.02)

    folds = sorted(fold_results.keys())
    # The macro average across folds is meaningless when fold_all is included
    # (fold="all" has no held-out split), so suppress it in that case.
    show_macro = "all" not in folds

    for ax, metric in zip(axes, _PLOT_METRICS):
        mat = []

        for fi, fid in enumerate(folds):
            vals = [
                float(np.nanmean(fold_results[fid][attack_name][eps][metric]))
                for eps in epsilons
            ]
            mat.append(vals)
            ax.plot(
                epsilons,
                vals,
                marker="o",
                linestyle="-",
                linewidth=1.5,
                color=_FOLD_CMAP((fi % 10) / 10.0),
                alpha=0.85,
                label=f"Fold {fid}",
            )

        if mat and show_macro:
            arr = np.array(mat, dtype=np.float64)
            macro = np.nanmean(arr, axis=0)
            n_f = arr.shape[0]
            sem = (
                (np.nanstd(arr, axis=0, ddof=1) / np.sqrt(n_f))
                if n_f > 1
                else np.zeros_like(macro)
            )
            ax.errorbar(
                epsilons,
                macro,
                yerr=sem,
                color="black",
                linewidth=2.2,
                linestyle="--",
                marker="s",
                capsize=4,
                zorder=10,
                label="Macro avg ± SEM",
            )

        ax.set_title(METRIC_LABELS[metric], fontsize=11)
        ax.set_xlabel("ε (L∞)")
        ax.set_ylabel(METRIC_LABELS[metric])
        ax.set_xticks(epsilons)
        ax.tick_params(axis="x", rotation=45)
        ax.grid(True, alpha=0.3)
        ax.legend(fontsize=8, loc="best")

    plt.tight_layout()
    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    plt.savefig(out_path, dpi=150, bbox_inches="tight")
    plt.close(fig)
    print(f"  → {out_path}")


