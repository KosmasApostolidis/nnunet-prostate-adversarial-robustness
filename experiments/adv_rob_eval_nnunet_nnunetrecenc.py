# CSV export
# ---------------------------------------------------------------------------
def save_csv(
    fold_results: Dict[int, Dict],
    epsilons: List[float],
    out_path: str,
    attacks: Dict | None = None,
) -> None:
    attacks = attacks if attacks is not None else ATTACKS
    folds = sorted(fold_results.keys())
    header = (
        ["fold", "attack", "epsilon"]
        + [f"{m}_mean" for m in METRICS]
        + [f"{m}_sem" for m in METRICS]
    )
    with open(out_path, "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(header)
        for fid in folds:
            for atk in attacks:
                for eps in epsilons:
                    row = [fid, atk, eps]
                    for m in METRICS:
                        vals = np.array(
                            fold_results[fid][atk][eps][m], dtype=np.float64
                        )
                        vals = vals[np.isfinite(vals)]
                        row.append(f"{float(vals.mean()):.6f}" if len(vals) else "nan")
                    for m in METRICS:
                        vals = np.array(
                            fold_results[fid][atk][eps][m], dtype=np.float64
                        )
                        vals = vals[np.isfinite(vals)]
                        n = len(vals)
                        sem = float(vals.std(ddof=1) / np.sqrt(n)) if n > 1 else 0.0
                        row.append(f"{sem:.6f}")
                    w.writerow(row)
    print(f"  → {out_path}")


def save_percase_csv(
    fold_results: Dict[int, Dict],
    fold_case_ids: Dict[int, List[str]],
    epsilons: List[float],
    out_path: str,
    attacks: Dict | None = None,
) -> None:
    """Long-format per-case metrics: one row per (fold, case_id, attack, epsilon).

    ``fold_case_ids[fid]`` is aligned index-for-index with the per-case metric
    lists in ``fold_results[fid][atk][eps][m]`` (both produced by evaluate_fold).
    """
    attacks = attacks if attacks is not None else ATTACKS
    header = ["fold", "case_id", "attack", "epsilon"] + list(METRICS)
    with open(out_path, "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(header)
        for fid in sorted(fold_results.keys()):
            case_ids = fold_case_ids[fid]
            res = fold_results[fid]
            for atk in attacks:
                for eps in epsilons:
                    for i, cid in enumerate(case_ids):
                        row = [fid, cid, atk, eps]
                        for m in METRICS:
                            v = float(res[atk][eps][m][i])
                            row.append(f"{v:.6f}" if np.isfinite(v) else "nan")
                        w.writerow(row)
    print(f"  → {out_path}")


# ---------------------------------------------------------------------------
# Main evaluation runner
# ---------------------------------------------------------------------------
def run(
    dataset_key: str,
    trainer_key: str,
    args,
    device: torch.device,
    force_fold_all: bool = False,
    attacks: Dict | None = None,
    epsilons: List[float] | None = None,
) -> None:
    attacks = attacks if attacks is not None else ATTACKS
    epsilons = epsilons if epsilons is not None else EPSILONS
    ds_cfg = DATASETS[dataset_key]
    trainer_name = TRAINERS[trainer_key]
    model_display = f"{TRAINER_DISPLAY[trainer_key]}"
    prefix = f"{dataset_key}_{trainer_key}"

    results_dir = os.path.join(
        NNUNET_PATHS, "nnUNet_results", ds_cfg["dataset_name"], trainer_name
    )
    data_dir = os.path.join(
        NNUNET_PATHS,
        "nnUNet_preprocessed",
        ds_cfg["dataset_name"],
        ds_cfg["data_subdir"],
    )
    splits_json = os.path.join(
        NNUNET_PATHS, "nnUNet_preprocessed", ds_cfg["dataset_name"], "splits_final.json"
    )

    if not os.path.isdir(results_dir):
        print(f"[SKIP] {prefix}: results dir not found ({results_dir})")
        return

    splits = load_splits(splits_json)
    out_dir = os.path.abspath(args.output_dir)
    csv_out_dir = os.path.join(out_dir, "data")
    fig_out_dir = os.path.join(out_dir, "figures")
    os.makedirs(csv_out_dir, exist_ok=True)
    os.makedirs(fig_out_dir, exist_ok=True)

    print(f"\n{'=' * 60}")
    print(f"  Dataset : {dataset_key}  ({ds_cfg['dataset_name']})")
    print(f"  Trainer : {trainer_key}  ({trainer_name})")
    print(f"{'=' * 60}")

    fold_results: Dict = {}
    fold_case_ids: Dict = {}

    # Models fine-tuned with fold="all" have no held-out split (nnU-Net trains
    # and validates on the full dataset in that mode) — evaluate on all cases.
    # Prefer standard 5-fold CV whenever fold_0 exists, even if a sibling
    # fold_all checkpoint is also present (e.g. clean models trained both ways),
    # unless force_fold_all requests the fold_all checkpoint explicitly (used to
    # compare clean vs. PGD-AT models on the same fold="all" training regime).
    fold_all_ckpt = os.path.isfile(
        os.path.join(results_dir, "fold_all", "checkpoint_final.pth")
    )
    if force_fold_all and fold_all_ckpt:
        fold_ids: list = ["all"]
        all_case_ids = sorted(set(splits[0]["train"]) | set(splits[0]["val"]))
    elif os.path.isfile(os.path.join(results_dir, "fold_0", "checkpoint_final.pth")):
        fold_ids = list(range(len(splits)))
        all_case_ids = None
    elif fold_all_ckpt:
        fold_ids = ["all"]
        all_case_ids = sorted(set(splits[0]["train"]) | set(splits[0]["val"]))
    else:
        fold_ids = list(range(len(splits)))
        all_case_ids = None

    for fold_id in fold_ids:
        ckpt = os.path.join(results_dir, f"fold_{fold_id}", "checkpoint_final.pth")
        if not os.path.isfile(ckpt):
            print(f"  [SKIP] fold {fold_id}: checkpoint not found")
            continue

        print(f"\n  [Fold {fold_id}] loading checkpoint …")
        model, div_factors, _ = build_model(ckpt, device)

        if fold_id == "all":
            case_ids = all_case_ids
            print(
                f"  [Fold all] {len(case_ids)} cases (fold=all: no held-out split, evaluated on full training set)"
            )
        else:
            case_ids = splits[fold_id]["val"]
            print(f"  [Fold {fold_id}] {len(case_ids)} val cases")

        fold_results[fold_id], fold_case_ids[fold_id] = evaluate_fold(
            model=model,
            div_factors=div_factors,
            num_classes=ds_cfg["num_classes"],
            data_dir=data_dir,
            case_ids=case_ids,
            epsilons=epsilons,
            device=device,
            max_cases=args.max_cases,
            attacks=attacks,
            batch_size=getattr(args, "batch_size", 1),
            autocast_dtype=torch.bfloat16 if getattr(args, "bf16", False) else None,
        )

        del model
        gc.collect()
        if device.type == "cuda":
            torch.cuda.empty_cache()

    if not fold_results:
        print(f"  [WARN] No fold results for {prefix}")
        return

    # CSV — aggregate (mean/sem) and per-case (long format for patient-level plots)
    save_csv(
        fold_results,
        epsilons,
        os.path.join(csv_out_dir, f"{prefix}_adv_rob.csv"),
        attacks=attacks,
    )
    save_percase_csv(
        fold_results,
        fold_case_ids,
        epsilons,
        os.path.join(csv_out_dir, f"{prefix}_percase.csv"),
        attacks=attacks,
    )

    # 2×2 plots — one per attack
    ds_short = dataset_key.upper()
    for atk_name in attacks:
        title = (
            f"{model_display} — {ds_short}\n"
            f"{atk_name} Attack  |  per-fold metrics vs ε (L∞)"
        )
        plot_2x2(
            fold_results=fold_results,
            epsilons=epsilons,
            title=title,
            attack_name=atk_name,
            out_path=os.path.join(fig_out_dir, f"{prefix}_{atk_name.lower()}_2x2.png"),
        )


# ---------------------------------------------------------------------------
# CLI
# ---------------------------------------------------------------------------
def main() -> None:
    parser = argparse.ArgumentParser(
        description="Adversarial robustness evaluation for nnU-Net UNet and ResEnc models"
    )
    parser.add_argument(
        "--datasets",
        nargs="+",
        choices=list(DATASETS.keys()),
        default=list(DATASETS.keys()),
        help="Datasets to evaluate (default: all)",
    )
    parser.add_argument(
        "--trainers",
        nargs="+",
        choices=list(TRAINERS.keys()),
        default=list(TRAINERS.keys()),
        help="Trainer variants to evaluate (default: all)",
    )
    parser.add_argument(
        "--output-dir",
        type=str,
        default="results/adv_rob_eval_results",
        help="Directory for CSV and plot outputs",
    )
    parser.add_argument(
        "--max-cases",
        type=int,
        default=None,
        help="Limit validation cases per fold (useful for quick testing)",
    )
    parser.add_argument(
        "--device",
        type=str,
        default=None,
        help="Device override, e.g. 'cpu' or 'cuda:1'",
    )
    parser.add_argument(
        "--batch-size",
        type=int,
        default=1,
        help="cases attacked per GPU forward (throughput only; memory-bound)",
    )
    parser.add_argument(
        "--bf16",
        action="store_true",
        help="run attack generation under bf16 autocast (faster on GPU; metric "
        "forward stays fp32). Validate drift with measure_bf16_autocast.py first",
    )
    parser.add_argument(
        "--fold-all",
        action="store_true",
        help="evaluate the fold_all checkpoint only (no held-out split); default "
        "prefers 5-fold CV when fold_0 checkpoints exist",
    )
    parser.add_argument(
        "--attacks",
        nargs="+",
        choices=list(ATTACK_CLI),
        default=list(ATTACK_CLI),
        help="built-in attacks to run (default: all three)",
    )
    args = parser.parse_args()

    device = (
        torch.device(args.device)
        if args.device
        else torch.device("cuda" if torch.cuda.is_available() else "cpu")
    )
    print(f"Device: {device}")

    selected_attacks = {ATTACK_CLI[a]: ATTACKS[ATTACK_CLI[a]] for a in args.attacks}
    print(f"Attacks: {list(selected_attacks)}")

    for ds_key in args.datasets:
        for tr_key in args.trainers:
            run(
                ds_key,
                tr_key,
                args,
                device,
                force_fold_all=args.fold_all,
                attacks=selected_attacks,
            )

    print("\nAll evaluations complete.")


if __name__ == "__main__":
    main()
